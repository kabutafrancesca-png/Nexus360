-- =====================================================================
-- Infratel Nexus 360  |  SQLite schema  (local development fallback)
-- Run via:  python db/init_local.py
--
-- Differences from schema.sql (Postgres):
--   • No ENUMs  — stored as TEXT with CHECK constraints instead
--   • No UUID functions — app generates uuid4() in Python before inserting
--   • No gen_random_uuid() / pgcrypto / pg_trgm extensions
--   • No GENERATED ALWAYS AS STORED columns — app calculates and writes them
--   • TIMESTAMPTZ → TEXT (ISO-8601 strings, e.g. '2026-11-25T10:00:00')
--   • BIGSERIAL → INTEGER PRIMARY KEY AUTOINCREMENT
--   • SERIAL    → INTEGER PRIMARY KEY AUTOINCREMENT
--   • ON CONFLICT DO NOTHING supported natively
--   • No CREATE EXTENSION, no trigger functions (triggers kept simple)
-- =====================================================================
PRAGMA foreign_keys = ON;
PRAGMA journal_mode = WAL;   -- safer concurrent reads during dev

