-- =====================================================================
-- Convenience views  (mirror the Postgres views)
-- =====================================================================
CREATE VIEW IF NOT EXISTS v_pipeline_summary AS
SELECT maturity, stage, COUNT(*) AS deals,
       SUM(amount) AS total_amount,
       SUM(weighted_amount) AS weighted_amount
FROM opportunities
WHERE stage NOT IN ('closed_won','closed_lost')
GROUP BY maturity, stage;

CREATE VIEW IF NOT EXISTS v_vertical_revenue AS
SELECT v.id AS vertical_id, v.name AS vertical,
       COUNT(a.id) AS accounts,
       COALESCE(SUM(a.contracted_revenue), 0) AS revenue
FROM verticals v
LEFT JOIN accounts a ON a.vertical_id = v.id AND a.status != 'churned'
GROUP BY v.id, v.name
ORDER BY revenue DESC;

CREATE VIEW IF NOT EXISTS v_contracts_expiring AS
SELECT c.*,
       a.company_name,
       CAST(julianday(c.expiry_date) - julianday('now') AS INTEGER) AS days_to_expiry
FROM contracts c
JOIN accounts a ON a.id = c.account_id
WHERE c.status = 'active'
  AND julianday(c.expiry_date) <= julianday('now') + 180;
